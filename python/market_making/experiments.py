"""Reproducible multi-seed strategy comparison for the synthetic simulator."""

from __future__ import annotations

import argparse
import csv
import json
from collections.abc import Iterable
from dataclasses import asdict, replace
from pathlib import Path
from statistics import mean, pstdev

from market_making.simulator import BacktestConfig, BacktestResult, StrategyName, run_backtest

RESULT_FIELDS = list(BacktestResult.__dataclass_fields__)
NUMERIC_METRICS = (
    "mark_to_market_pnl",
    "gross_spread_capture_pnl",
    "post_fill_markout_pnl",
    "fills",
    "max_abs_inventory",
    "final_inventory",
    "negative_markout_quantity",
    "negative_markout_loss",
)


def _summary(rows: list[BacktestResult]) -> dict[str, float]:
    return {
        metric: {
            "mean": round(mean(getattr(row, metric) for row in rows), 4),
            "population_stddev": round(pstdev(getattr(row, metric) for row in rows), 4),
            "minimum": min(getattr(row, metric) for row in rows),
            "maximum": max(getattr(row, metric) for row in rows),
        }
        for metric in NUMERIC_METRICS
    }


def run_multi_seed_experiment(
    seeds: Iterable[int], config: BacktestConfig | None = None
) -> dict[StrategyName, list[BacktestResult]]:
    config = config or BacktestConfig()
    seed_list = list(seeds)
    if not seed_list:
        raise ValueError("at least one seed is required")
    return {
        strategy: [run_backtest(replace(config, seed=seed), strategy) for seed in seed_list]
        for strategy in ("fixed_spread", "inventory_aware")
    }


def write_experiment_artifacts(
    output_dir: Path,
    seeds: Iterable[int],
    config: BacktestConfig | None = None,
) -> dict[str, Path]:
    config = config or BacktestConfig()
    seed_list = list(seeds)
    outcomes = run_multi_seed_experiment(seed_list, config)
    output_dir.mkdir(parents=True, exist_ok=True)

    csv_path = output_dir / "multi_seed_results.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=["seed", *RESULT_FIELDS])
        writer.writeheader()
        for strategy_rows in outcomes.values():
            for seed, result in zip(seed_list, strategy_rows, strict=True):
                writer.writerow({"seed": seed, **asdict(result)})

    summary = {
        "data_scope": (
            "synthetic deterministic replay only; not live or historical trading performance"
        ),
        "seed_count": len(seed_list),
        "seeds": seed_list,
        "config": asdict(config),
        "strategies": {strategy: _summary(rows) for strategy, rows in outcomes.items()},
        "fill_model": {
            "description": (
                "A marketable order reaches the quote with a bounded probability based on "
                "crossing depth. This is a queue-position proxy, not a real exchange queue."
            ),
            "post_fill_markout": (
                "One-step markout measures the next synthetic mid relative to the fill price; "
                "negative values indicate adverse post-fill movement."
            ),
        },
    }
    json_path = output_dir / "multi_seed_summary.json"
    json_path.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    fixed = summary["strategies"]["fixed_spread"]
    inventory = summary["strategies"]["inventory_aware"]
    report_lines = [
        "# Synthetic Multi-Seed Experiment",
        "",
        "Generated by `python -m market_making.experiments "
        f"--seeds {len(seed_list)} --steps {config.steps}`.",
        "",
        "## Scope",
        "",
        f"This report compares two strategies over the same {len(seed_list)} seeded "
        "**synthetic** replays. It is an engineering validation artifact, not evidence "
        "of live-market performance.",
        "",
        "## Aggregate results",
        "",
        "| Metric | Fixed spread mean | Inventory-aware mean |",
        "| --- | ---: | ---: |",
        "| Mark-to-market P&L (ticks) | "
        f"{fixed['mark_to_market_pnl']['mean']} | "
        f"{inventory['mark_to_market_pnl']['mean']} |",
        "| Gross spread capture (ticks) | "
        f"{fixed['gross_spread_capture_pnl']['mean']} | "
        f"{inventory['gross_spread_capture_pnl']['mean']} |",
        "| One-step post-fill markout (ticks) | "
        f"{fixed['post_fill_markout_pnl']['mean']} | "
        f"{inventory['post_fill_markout_pnl']['mean']} |",
        f"| Filled quantity | {fixed['fills']['mean']} | {inventory['fills']['mean']} |",
        "| Max absolute inventory | "
        f"{fixed['max_abs_inventory']['mean']} | "
        f"{inventory['max_abs_inventory']['mean']} |",
        "| Negative-markout quantity | "
        f"{fixed['negative_markout_quantity']['mean']} | "
        f"{inventory['negative_markout_quantity']['mean']} |",
        "| Negative-markout loss (ticks) | "
        f"{fixed['negative_markout_loss']['mean']} | "
        f"{inventory['negative_markout_loss']['mean']} |",
        "",
        "## Interpretation",
        "",
        "The two strategies see identical synthetic order flow. The inventory-aware rule "
        "shifts its reservation price and may widen as inventory grows. It can trade fill "
        "opportunity for lower inventory risk. Differences are conditional on the explicit "
        "synthetic generator, bounded queue proxy, and one-step directional-pressure "
        "assumption. They are not a prediction of production returns.",
        "",
    ]
    report = "\n".join(report_lines)
    report_path = output_dir / "multi_seed_report.md"
    report_path.write_text(report, encoding="utf-8")
    return {"csv": csv_path, "json": json_path, "report": report_path}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seeds", type=int, default=100, help="number of seeds beginning at one")
    parser.add_argument("--steps", type=int, default=500, help="events per synthetic replay")
    parser.add_argument("--output-dir", type=Path, default=Path("artifacts"))
    args = parser.parse_args()
    if args.seeds <= 0:
        parser.error("--seeds must be positive")
    paths = write_experiment_artifacts(
        args.output_dir, range(1, args.seeds + 1), BacktestConfig(steps=args.steps)
    )
    print(json.dumps({name: str(path) for name, path in paths.items()}, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
